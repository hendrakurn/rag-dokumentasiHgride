print("1. Membaca dokumentasi HGrid247 dari web...")
loader = WebBaseLoader(
    web_paths=urls,
    # Filter semua tag konten termasuk tabel, list, paragraf, heading
    # Hindari terlalu ketat agar konten seperti Custom Source tidak hilang
    bs_kwargs=dict(
        parse_only=bs4.SoupStrainer(
            ["body", "article", "main", "section", "div",
             "p", "h1", "h2", "h3", "h4", "h5", "h6",
             "table", "thead", "tbody", "tr", "td", "th",
             "ul", "ol", "li", "pre", "code", "blockquote"]
        )
    ),
)
documents = loader.load()
print(f"   Berhasil memuat {len(documents)} halaman web.")

# ============================================================
# FASE 2: CHUNKING (PECAH TEKS MENJADI POTONGAN KECIL)
# ============================================================

print(" 2. Memecah teks menjadi potongan kecil (chunking)...")
text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=700,      # Ukuran tiap potongan (karakter)
    chunk_overlap=100,   # Overlap antar potongan agar konteks tidak hilang
)
docs = text_splitter.split_documents(documents)
print(f"   Berhasil membuat {len(docs)} potongan teks.")

# Tampilkan preview potongan pertama untuk verifikasi
if docs:
    print(f"\n   Preview potongan pertama:\n   ---")
    print(f"   {docs[0].page_content[:300]}...")
    print(f"   ---\n")

# ============================================================
# FASE 3: EMBEDDING & SIMPAN KE QDRANT
# ============================================================

print("3. Membuat embedding dan menyimpan ke Qdrant (localhost:6333)...")
embeddings = HuggingFaceEmbeddings(model_name="all-MiniLM-L6-v2")

qdrant = QdrantVectorStore.from_documents(
    docs,
    embeddings,
    url="http://localhost:6333",
    prefer_grpc=False,
    collection_name="hgrid247_docs",
    force_recreate=True,  # Selalu buat ulang collection agar data selalu fresh
)

print("Selesai! Data dokumentasi HGrid247 sudah tersimpan di Qdrant.")
print(f"   Collection: hgrid247_docs")
print(f"   Total chunks: {len(docs)}")
